#!/usr/bin/env python3
"""End-to-end A/B for a single (large) model not in ocaml/golden — e.g. the
P=16,A=7 scaling anchor generated by scripts/gen_scaling_models.py.

Times `camdl pfilter` resolved (default) vs unresolved (CAMDL_EVAL_UNRESOLVED=1)
at one or more particle counts. The model load (compile/parse of the big IR) is
~1s and switch-independent, negligible vs the multi-second runs here, so the raw
ratio at a given particle count is ~the inner-loop ratio.

Appends rows to end_to_end_scale_runs.tsv.

  python3 bench_scale_point.py --ir /tmp/pmmh16.ir.json --label pmmh_P16A7 \
      --scenario baseline --data weekly_cases=/tmp/pmmh16_obs/weekly_cases.tsv \
      --particles 1000,2000 --reps 3
"""
import argparse, os, statistics, subprocess, time
from pathlib import Path

HERE = Path(__file__).resolve().parent
CAMDL = HERE.parents[4] / "rust" / "target" / "release" / "camdl"


def run_once(ir, scenario, datas, p, unresolved, seed):
    env = dict(os.environ, CAMDL_SKIP_VERSION_CHECK="1")
    if unresolved:
        env["CAMDL_EVAL_UNRESOLVED"] = "1"
    else:
        env.pop("CAMDL_EVAL_UNRESOLVED", None)
    cmd = [str(CAMDL), "pfilter", ir, "--scenario", scenario,
           "--particles", str(p), "--dt", "1", "--seed", str(seed)]
    for d in datas:
        cmd += ["--data", d]
    t0 = time.perf_counter()
    r = subprocess.run(cmd, env=env, capture_output=True, text=True)
    dt = time.perf_counter() - t0
    if r.returncode != 0:
        raise RuntimeError(r.stderr[-400:])
    return dt


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ir", required=True)
    ap.add_argument("--label", required=True)
    ap.add_argument("--scenario", required=True)
    ap.add_argument("--data", action="append", default=[])
    ap.add_argument("--particles", default="1000,2000")
    ap.add_argument("--reps", type=int, default=3)
    args = ap.parse_args()
    counts = [int(x) for x in args.particles.split(",")]

    rows = []
    for p in counts:
        for switch, unres in [("resolved", False), ("unresolved", True)]:
            run_once(args.ir, args.scenario, args.data, p, unres, 1)   # warmup
            ts = []
            for rep in range(args.reps):
                secs = run_once(args.ir, args.scenario, args.data, p, unres, 1 + rep)
                ts.append(secs)
                rows.append((args.label, switch, p, rep, secs))
                print(f"{args.label} {switch:11s} p={p:<6d} rep={rep} {secs:7.2f}s")
            print(f"  -> {switch} p={p} median={statistics.median(ts):.2f}s")

    out = HERE / "end_to_end_scale_runs.tsv"
    new = not out.exists()
    with open(out, "a") as f:
        if new:
            f.write("model\tswitch\tparticles\trep\tsecs\n")
        for r in rows:
            f.write("\t".join(str(x) for x in r) + "\n")

    def med(sw, p):
        return statistics.median([s for (_, w, pp, _, s) in rows if w == sw and pp == p])
    print("\n── scale-point summary ──")
    for p in counts:
        ro, un = med("resolved", p), med("unresolved", p)
        print(f"  p={p:<6d} resolved={ro:.2f}s unresolved={un:.2f}s  raw_ratio={un/ro:.2f}x")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
